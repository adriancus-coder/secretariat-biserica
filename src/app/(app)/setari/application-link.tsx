"use client";

import { useEffect, useRef, useState, useSyncExternalStore } from "react";
import { createPortal } from "react-dom";
import { Icon } from "@/components/shell/icons";
import { CopyButton } from "@/components/ui/copy-button";
import { TextAreaField } from "@/components/ui/fields";
import { FormMessage } from "@/components/ui/form-bits";
import { useActionForm } from "@/components/ui/use-action-form";
import { sendApplicationLinkAction } from "@/server/actions/application-link";
import { DownloadLink } from "@/components/ui/download";
import { MIME } from "@/lib/download";

export interface ApplicationLinkProps {
  url: string;
  slug: string;
  /** The QR code as SVG markup, generated on the server. */
  qrSvg: string;
  /** The QR code as a PNG data URL, for "Descarcă PNG". */
  qrPng: string;
  open: boolean;
  emailConfigured: boolean;
  /** The fixed subject and the fixed start and end of the message. */
  subject: string;
  frame: { start: string; end: string };
}

/** QR code of the public application link, with download, copy, share, poster and e-mail. */
export function ApplicationLink({ url, slug, qrSvg, qrPng, open, emailConfigured, subject, frame }: ApplicationLinkProps) {
  return (
    <div className="card application-link">
      <h3 id="cerere">Linkul cererii de membru</h3>
      {open ? null : (
        <div className="alert mb-3" role="status">
          Linkul este închis: cine îl deschide vede că biserica nu primește cereri online. Porniți „Primește cereri de membru online” în
          Organizația.
        </div>
      )}
      <div className="qr-row">
        {/* Generated by the qrcode package on the server: plain SVG paths, no scripts. */}
        <div className="qr" role="img" aria-label={`Cod QR pentru ${url}`} dangerouslySetInnerHTML={{ __html: qrSvg }} />
        <div className="min-w-0">
          <p className="hint !mt-0 mb-3">Scanați codul cu telefonul sau trimiteți linkul celor care vor să devină membri.</p>
          <p className="break-all mb-3 text-sm">
            <a href={url} target="_blank" rel="noopener noreferrer">
              {url}
            </a>
          </p>
          <div className="flex flex-wrap gap-2">
            <DownloadLink file={qrPng} filename={`cerere-${slug}.png`} mime={MIME.png}>
              Descarcă PNG
            </DownloadLink>
            <CopyButton text={url} label="Copiază linkul" className="btn" />
            <ShareButton url={url} />
            <DownloadLink file="/pdf/afis-cerere" filename="afis-cerere.pdf" mime={MIME.pdf} inline>
              Afiș PDF
            </DownloadLink>
            <SendLinkButton configured={emailConfigured} subject={subject} frame={frame} />
          </div>
        </div>
      </div>
    </div>
  );
}

const noSubscribe = () => () => {};

/** Web Share API with the link; where it is missing, the link is copied instead. */
function ShareButton({ url }: { url: string }) {
  const [note, setNote] = useState("");
  async function share() {
    setNote("");
    if (typeof navigator.share === "function") {
      try {
        await navigator.share({ title: "Cerere de membru", url });
        return;
      } catch (err) {
        // Closing the share sheet is not an error.
        if (err instanceof DOMException && err.name === "AbortError") return;
      }
    }
    try {
      await navigator.clipboard.writeText(url);
      setNote("Linkul a fost copiat.");
    } catch {
      setNote("Linkul nu a putut fi copiat.");
    }
  }
  return (
    <>
      <button type="button" className="btn" onClick={share}>
        Partajează
      </button>
      {note ? (
        <span role="status" className="self-center text-xs text-ink-3">
          {note}
        </span>
      ) : null}
    </>
  );
}

function SendLinkButton({ configured, subject, frame }: { configured: boolean; subject: string; frame: { start: string; end: string } }) {
  const dialog = useRef<HTMLDialogElement>(null);
  // A new key remounts the form, so every opening starts from the defaults.
  const [formKey, setFormKey] = useState(0);
  // document.body exists only in the browser: the portal renders after hydration.
  const mounted = useSyncExternalStore(noSubscribe, () => true, () => false);

  if (!configured) {
    return (
      <span className="inline-flex flex-col gap-0.5">
        <button type="button" className="btn" disabled aria-describedby="link-send-off">
          <Icon name="email" className="size-[18px]" /> Trimite linkul pe e-mail
        </button>
        <span id="link-send-off" className="text-xs text-ink-3">
          Trimiterea pe e-mail nu este configurată.
        </span>
      </span>
    );
  }
  return (
    <>
      <button
        type="button"
        className="btn"
        onClick={() => {
          setFormKey((k) => k + 1);
          dialog.current?.showModal();
        }}
      >
        <Icon name="email" className="size-[18px]" /> Trimite linkul pe e-mail
      </button>
      {/* The panel sits inside the settings form: the dialog (with its own form) goes to <body>. */}
      {mounted
        ? createPortal(
            <dialog ref={dialog} className="dialog" aria-labelledby="link-send-title">
              <SendLinkForm key={formKey} subject={subject} frame={frame} onClose={() => dialog.current?.close()} />
            </dialog>,
            document.body,
          )
        : null}
    </>
  );
}

function SendLinkForm({ subject, frame, onClose }: { subject: string; frame: { start: string; end: string }; onClose: () => void }) {
  const { state, pending, onSubmit } = useActionForm(sendApplicationLinkAction);
  const e = state.errors ?? {};
  useEffect(() => {
    if (!state.ok) return;
    const t = setTimeout(onClose, 1500);
    return () => clearTimeout(t);
  }, [state, onClose]);

  return (
    <form onSubmit={onSubmit} noValidate>
      <h3 id="link-send-title">Trimite linkul cererii</h3>
      <FormMessage state={state} />
      <TextAreaField
        name="adrese"
        label="Adrese de e-mail"
        rows={2}
        placeholder="ex. ana@exemplu.ro, ion@exemplu.no"
        hint="Separate prin virgulă sau pe rânduri diferite. Toți destinatarii primesc același mesaj."
        error={e.adrese}
        className="[&_textarea]:!min-h-[64px]"
        autoComplete="off"
        spellCheck={false}
      />
      <p className="hint mb-2">
        Subiect: <b>{subject}</b>
      </p>
      <TextAreaField
        name="nota"
        label="Mesaj (opțional)"
        defaultValue={state.values?.nota ?? ""}
        error={e.nota}
        rows={4}
        maxLength={1000}
        hint={`E-mailul începe cu „${frame.start}”, conține linkul și se încheie cu „${frame.end}”. Aici puteți adăuga câteva rânduri (cel mult 1000 de caractere).`}
      />
      <div className="actions">
        <button type="submit" className="btn btn-primary" disabled={pending || state.ok}>
          <Icon name="email" className="size-[18px]" /> {pending ? "Se trimite…" : "Trimite"}
        </button>
        <button type="button" className="btn" onClick={onClose}>
          Închide
        </button>
      </div>
    </form>
  );
}
